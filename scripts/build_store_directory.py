#!/usr/bin/env python3
"""Compila Directorio_PBT.xlsx a un cruce CeCo/Tienda local, sin dependencias."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET
from zipfile import ZipFile
ROOT=Path(__file__).resolve().parents[1]
OUTPUT=ROOT/'js/store-directory.js'
NS={'m':'http://schemas.openxmlformats.org/spreadsheetml/2006/main'}

def read_directory(path):
    with ZipFile(path) as z:
        shared=[]
        if 'xl/sharedStrings.xml' in z.namelist():
            shared=[''.join(node.itertext()) for node in ET.fromstring(z.read('xl/sharedStrings.xml')).findall('m:si',NS)]
        workbook=ET.fromstring(z.read('xl/workbook.xml'))
        sheet=workbook.find('m:sheets/m:sheet',NS)
        rid=sheet.attrib['{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id']
        relationships=ET.fromstring(z.read('xl/_rels/workbook.xml.rels'))
        target=next(r.attrib['Target'] for r in relationships if r.attrib['Id']==rid)
        target=target.lstrip('/') if target.startswith('/') else 'xl/'+target
        rows=[]
        for row in ET.fromstring(z.read(target)).findall('m:sheetData/m:row',NS):
            values={}
            for cell in row.findall('m:c',NS):
                col=re.sub(r'\d','',cell.attrib['r']);value=cell.find('m:v',NS)
                if cell.attrib.get('t')=='inlineStr':text=''.join(t.text or '' for t in cell.findall('.//m:t',NS))
                elif value is None:text=''
                elif cell.attrib.get('t')=='s':text=shared[int(value.text)]
                else:text=value.text or ''
                values[col]=text.strip()
            if values.get('A') or values.get('B'):rows.append((values.get('A',''),values.get('B','')))
    if not rows or [v.casefold() for v in rows[0]]!=['ceco','tienda']:raise ValueError('Se requieren las columnas CeCo y Tienda')
    stores={}
    for code,name in rows[1:]:
        if re.fullmatch(r'\d+\.0',code):code=code[:-2]
        name=' '.join(name.split())
        if not re.fullmatch(r'\d{3,8}',code) or not name:raise ValueError('CeCo o nombre de tienda inválido')
        if code in stores:raise ValueError('CeCo duplicado: '+code)
        stores[code]=name
    if not stores:raise ValueError('Directorio vacío')
    return {'schema':1,'source':path.name,'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'stores':[list(row) for row in sorted(stores.items())]}

TEMPLATE=r'''/* Generated by scripts/build_store_directory.py from the supplied directory. */
(function(root){
 'use strict';
 const DATA=__DATA__;
 const normal=value=>String(value||'').normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLowerCase().replace(/\bdt\b/g,'').replace(/[^a-z0-9]+/g,' ').trim();
 const codes=new Map(DATA.stores),names=new Map();
 for(const [code,name] of DATA.stores){const key=normal(name);names.set(key,names.has(key)?null:code);}
 function lookup(value){
  const raw=String(value||''),match=raw.match(/^(?:CeCo\s+)?(\d{3,8})(?=\D|$)/i),code=match?match[1]:names.get(normal(raw))||'';
  return {code,name:codes.get(code)||(!match?raw:'')};
 }
 function label(value){const item=lookup(value);return item.code?item.code+(item.name?' · '+item.name:''):String(value||'');}
 const api={data:DATA,lookup,label,normal,codeOf:value=>lookup(value).code};
 if(typeof module!=='undefined'&&module.exports)module.exports=api;else root.PBT_DIRECTORY=api;
})(typeof globalThis!=='undefined'?globalThis:this);
'''

def compiled(data):return TEMPLATE.replace('__DATA__',json.dumps(data,ensure_ascii=False,separators=(',',':')))
def read_compiled(path=OUTPUT):
    text=path.read_text(encoding='utf-8');start=text.index(' const DATA=')+len(' const DATA=')
    data=json.JSONDecoder().raw_decode(text,start)[0]
    codes=[r[0] for r in data['stores']]
    assert data['schema']==1 and re.fullmatch('[0-9a-f]{64}',data['sha256'])
    assert codes and len(codes)==len(set(codes)) and all(re.fullmatch(r'\d{3,8}',r[0]) and r[1].strip() for r in data['stores'])
    assert text==compiled(data),'Directorio compilado modificado fuera del generador'
    return data

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--source',type=Path);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    if args.source:
        data=read_directory(args.source)
        if args.check:assert OUTPUT.read_text(encoding='utf-8')==compiled(data),'El directorio no coincide con el Excel'
        else:OUTPUT.write_text(compiled(data),encoding='utf-8')
    else:
        if not args.check:parser.error('Indica --source Directorio_PBT.xlsx o --check')
        data=read_compiled()
    print(json.dumps({'estado':'VERDE','tiendas_directorio':len(data['stores']),'sha256_fuente':data['sha256']},ensure_ascii=False))
if __name__=='__main__':main()
